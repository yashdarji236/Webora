test("Next.js App Router: Updates title, description, and icons (favicon) in AST", () => {
  const repoAnalysis = {
    framework: { name: "Next.js", slug: "nextjs-app", version: "14.2.0" },
    router: { type: "app" },
    structure: { importantFiles: ["app/layout.tsx"] },
  };

  const patch = generatePreviewMetadataPatch({
    repoAnalysis,
    targetPath: "app/layout.tsx",
    originalContent: sampleAppRouterLayout,
    metadata: {
      title: "New Enhanced Next.js Title",
      description: "Production ready metadata description for Next.js 14.",
      favicon: "/favicon.svg",
      canonical: "https://nextbrand.com",
    },
  });

  assert.equal(patch.status, "applied");
  assert.equal(patch.filePath, "app/layout.tsx");
  assert.equal(patch.targetFile, "app/layout.tsx");
  assert.ok(patch.proposedContent.includes('title: "New Enhanced Next.js Title"'));
  assert.ok(patch.proposedContent.includes('description: "Production ready metadata description for Next.js 14."'));
  assert.ok(patch.proposedContent.includes('icon: "/favicon.svg"'));
  assert.ok(patch.proposedContent.includes('canonical: "https://nextbrand.com"'));
  assert.ok(patch.diff.length > 0);
  assert.equal(patch.validation.valid, true);
});

test("Security & Pre-flight: Ensures patch.filePath and patch.targetFile are never undefined", () => {
  const patch = generatePreviewMetadataPatch({
    repoAnalysis: { framework: { slug: "react-vite" } },
    targetPath: "index.html",
    originalContent: sampleViteHtml,
    metadata: { title: "Title Test" },
  });

  const previewFix = {
    patch: {
      filePath: patch.filePath || patch.targetFile,
      targetFile: patch.targetFile || patch.filePath,
      proposedContent: patch.proposedContent,
    },
  };

  assert.ok(previewFix.patch.filePath, "filePath must be defined");
  assert.equal(previewFix.patch.filePath, "index.html");
  assert.equal(previewFix.patch.targetFile, "index.html");
});

test("Next.js App Router: Resolves layout.tsx target candidate", () => {
  const candidates = getPreviewTargetCandidates({
    framework: { slug: "nextjs-app" },
    structure: { importantFiles: ["src/app/layout.tsx"] },
  });
  assert.deepEqual(candidates, ["src/app/layout.tsx"]);
});

