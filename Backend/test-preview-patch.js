/**
 * Test Suite for Preview Patch Service & Metadata PR Generation
 * Verifies patch generation for Title, Favicon, Description, and PR bundling.
 */

import assert from "node:assert/strict";
import {
  generatePreviewMetadataPatch,
  getPreviewTargetCandidates,
} from "./src/services/ai-fix-engine/previewPatchService.js";
import { inspectHtml } from "./src/services/ai-fix-engine/rule-engine/parsers/htmlParser.js";

console.log("🧪 Starting Preview Metadata PR Patch Test Suite...\n");

let passed = 0;
let failed = 0;

function test(name, fn) {
  try {
    fn();
    console.log(`  ✓ ${name}`);
    passed++;
  } catch (err) {
    console.error(`  ✗ ${name}`);
    console.error(`    ${err.stack}`);
    failed++;
  }
}

// ─────────────────────────────────────────────────────────────
// 1. REACT + VITE (index.html) PATCHING
// ─────────────────────────────────────────────────────────────
console.log("▶ 1. React + Vite HTML Metadata & Favicon Patching:");

const sampleViteHtml = `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <link rel="icon" type="image/svg+xml" href="/vite.svg" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>Original Vite App</title>
  </head>
  <body>
    <div id="root"></div>
  </body>
</html>`;

test("React+Vite: Updates title, meta description, and favicon", () => {
  const repoAnalysis = {
    framework: { name: "React", slug: "react-vite" },
    router: { type: "spa" },
  };

  const patch = generatePreviewMetadataPatch({
    repoAnalysis,
    targetPath: "index.html",
    originalContent: sampleViteHtml,
    metadata: {
      title: "Optimized SEO Brand Title",
      description: "High converting meta description snippet for search engines.",
      favicon: "/custom-favicon.ico",
      canonical: "https://mysite.com",
    },
  });

  assert.equal(patch.status, "applied");
  assert.equal(patch.filePath, "index.html");
  assert.equal(patch.targetFile, "index.html");
  assert.ok(patch.diff.includes("+    <title>Optimized SEO Brand Title</title>"));
  assert.ok(patch.proposedContent.includes('href="/custom-favicon.ico"'));
  assert.ok(patch.proposedContent.includes('content="High converting meta description snippet for search engines."'));
  assert.ok(patch.proposedContent.includes('href="https://mysite.com"'));

  const parsed = inspectHtml(patch.proposedContent);
  assert.equal(parsed.title, "Optimized SEO Brand Title");
  assert.equal(parsed.description, "High converting meta description snippet for search engines.");
  assert.equal(parsed.favicon, "/custom-favicon.ico");
  assert.equal(parsed.canonical, "https://mysite.com");
  assert.ok(patch.changes.length >= 3);
});

test("React+Vite: Resolves index.html target candidate", () => {
  const candidates = getPreviewTargetCandidates({
    framework: { slug: "react-vite" },
    structure: { importantFiles: ["index.html"] },
  });
  assert.deepEqual(candidates, ["index.html"]);
});

